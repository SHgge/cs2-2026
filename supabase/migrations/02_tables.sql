-- cs2_02_tables — all tables: RLS enabled, NO policies, no grants to public/anon/authenticated.
-- Access happens only through SECURITY DEFINER functions in cs2_api.

create table cs2.settings (
  id                  smallint primary key default 1 check (id = 1),
  version             bigint not null default 1,               -- bumped by every mutation
  reg_closes_at       timestamptz not null,                    -- 2026-10-16 17:00 +08
  consent_deadline_at timestamptz not null,                    -- 2026-10-21 17:00 +08
  roster_freeze_at    timestamptz not null,                    -- 2026-10-22 16:00 +08 (draw)
  tokens_valid_until  timestamptz not null,                    -- 2026-10-25 18:00 +08
  registration_open   boolean not null default true,
  stream_url          text check (stream_url is null or stream_url ~ '^https://[^[:space:]]{1,300}$'),
  setup_code_hash     text not null check (setup_code_hash ~ '^[0-9a-f]{64}$'),
  setup_used_at       timestamptz,
  updated_at          timestamptz not null default now()
);

create table cs2.teams (
  id          integer primary key,
  code        text not null unique check (code ~ '^[a-z0-9]{1,16}$'),
  name        text not null unique check (char_length(name) between 1 and 40),
  pot         smallint check (pot between 1 and 3),
  is_teachers boolean not null default false,
  is_hidden   boolean not null default false,               -- test team: never shown publicly
  grp         text check (grp in ('A','B','V','G')),        -- written by draw publish
  seat        smallint check (seat between 1 and 3),        -- seat = pot
  check (is_hidden or pot is not null),
  check ((grp is null) = (seat is null)),
  unique (grp, seat)
);

create table cs2.team_access (
  team_id          integer primary key references cs2.teams(id) on delete cascade,
  token_sha256     text unique check (token_sha256 ~ '^[0-9a-f]{64}$'),   -- only the hash of the class link token
  token_issued_at  timestamptz,
  pin_bcrypt       text,                                                  -- bcrypt of the 4-digit teacher PIN
  pin_issued_at    timestamptz,
  pin_fails        integer not null default 0,              -- wrong PINs inside the sliding 15-min window
  pin_fail_times   timestamptz[] not null default '{}',     -- timestamps of those wrong PINs
  pin_fails_total  integer not null default 0,              -- wrong PINs since issue/reset (10 -> hard lock)
  pin_locked_until timestamptz,                             -- 5 wrong within 15 min -> locked 15 min
  pin_hard_locked  boolean not null default false,          -- until admin pin_reset
  version          integer not null default 1,              -- roster version (optimistic concurrency)
  confirmed_at     timestamptz,
  confirmed_by     text,                                    -- 'teacher' | 'admin:<label>'
  confirm_attest   jsonb,
  confirm_reason   text,
  locked           boolean not null default false,          -- admin lock
  unlocked_until   timestamptz,                             -- admin extension of the edit window
  updated_at       timestamptz not null default now()
);

create table cs2.players (
  id              bigint generated by default as identity primary key,
  team_id         integer not null references cs2.teams(id) on delete cascade,
  slot            smallint not null check (slot between 1 and 6),   -- 1-5 starters, 6 substitute
  first_name      text not null check (char_length(first_name) between 1 and 30),
  surname_initial text not null check (char_length(surname_initial) = 1),
  steam_nickname  text not null check (char_length(steam_nickname) between 2 and 32),
  steam_id64      text check (steam_id64 ~ '^7656119[0-9]{10}$'),
  is_captain      boolean not null default false,
  age13           boolean not null default false,
  consent_paper   boolean not null default false,   -- form 05 received (paper stays at school)
  consent_3a      boolean,                          -- form 05 row 3а
  consent_3b      boolean,                          -- form 05 row 3б (online stream; false -> alias)
  consent_3v      boolean,                          -- form 05 row 3в (voice online)
  alias           text check (alias is null or char_length(alias) between 1 and 32),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (team_id, slot)
);
create unique index players_nickname_uq on cs2.players (lower(steam_nickname));
create unique index players_steam_id64_uq on cs2.players (steam_id64) where steam_id64 is not null;
create unique index players_one_captain_uq on cs2.players (team_id) where is_captain;

create table cs2.matches (
  no          smallint primary key check (no between 1 and 20),
  day         smallint not null check (day in (1, 2)),
  stage       text not null check (stage in ('group','qf','sf','final','third')),
  code        text,
  grp         text check (grp in ('A','B','V','G')),
  station     text not null check (station in ('A','B')),
  start_at    timestamptz not null,
  end_at      timestamptz not null,
  src_a       text not null,                     -- 'seat:A1' | 'rank:A1' | 'W:13' | 'L:17'
  src_b       text not null,
  status      text not null default 'scheduled' check (status in ('scheduled','live','reported','final')),
  score_a     smallint check (score_a >= 0),
  score_b     smallint check (score_b >= 0),
  ot          boolean not null default false,
  forfeit     text check (forfeit in ('a','b')),  -- side that LOST by forfeit
  team_a      integer references cs2.teams(id),
  team_b      integer references cs2.teams(id),
  reported_at timestamptz,
  reported_by text,
  updated_at  timestamptz not null default now(),
  check ((stage = 'group') = (grp is not null)),
  check (end_at > start_at)
);
create index matches_team_a_idx on cs2.matches (team_a);
create index matches_team_b_idx on cs2.matches (team_b);

create table cs2.draws (
  id           bigint generated by default as identity primary key,
  status       text not null check (status in ('committed','computed','published','void')),
  method       text not null default 'commit' check (method in ('commit','manual')),
  commit_hash  text check (commit_hash ~ '^[0-9a-f]{64}$'),
  secret       text check (secret ~ '^[0-9a-f]{64}$'),
  inputs       jsonb,          -- {code: n}
  inputs_str   text,           -- '12a=1234,11a=5,…'
  seed         text,
  keys         jsonb,          -- {code: hex}
  groups       jsonb,          -- {A:[code,code,code], …}
  reason       text,           -- manual draw reason
  committed_at timestamptz,
  computed_at  timestamptz,
  published_at timestamptz,
  voided_at    timestamptz,
  void_reason  text,
  created_at   timestamptz not null default now()
);
create unique index draws_one_active_uq on cs2.draws ((true)) where status <> 'void';

create table cs2.group_decisions (
  grp         text primary key check (grp in ('A','B','V','G')),
  lot         integer[],       -- lot order of team ids (chief referee, tie-break step 5)
  lot_reason  text,
  lot_at      timestamptz,
  approved    boolean not null default false,
  approved_at timestamptz,
  updated_at  timestamptz not null default now()
);

create table cs2.referee_access (
  id           bigint generated by default as identity primary key,
  label        text not null check (char_length(label) between 1 and 60),
  station      text check (station in ('A','B')),   -- null = chief referee (all stations)
  token_sha256 text not null unique check (token_sha256 ~ '^[0-9a-f]{64}$'),
  valid_from   timestamptz not null default '2026-10-24 07:00:00+08',
  valid_until  timestamptz not null default '2026-10-25 18:00:00+08',
  active       boolean not null default true,
  created_at   timestamptz not null default now()
);

create table cs2.admins (
  id            bigint generated by default as identity primary key,
  label         text not null check (char_length(label) between 1 and 60),
  secret_bcrypt text not null,
  created_at    timestamptz not null default now(),
  last_login_at timestamptz
);
create unique index admins_label_uq on cs2.admins (lower(label));

create table cs2.admin_sessions (
  token_sha256 text primary key check (token_sha256 ~ '^[0-9a-f]{64}$'),
  admin_id     bigint not null references cs2.admins(id) on delete cascade,
  created_at   timestamptz not null default now(),
  expires_at   timestamptz not null
);
create index admin_sessions_admin_id_idx on cs2.admin_sessions (admin_id);

create table cs2.announcements (
  id         bigint generated by default as identity primary key,
  text       text not null check (char_length(text) between 1 and 500),
  level      text not null default 'info' check (level in ('info','warn')),
  created_at timestamptz not null default now(),
  created_by text,
  hidden_at  timestamptz
);

create table cs2.audit_log (
  id       bigint generated by default as identity primary key,
  at       timestamptz not null default now(),
  actor    text not null,          -- 'admin:<label>' | 'class:<code>' | 'ref:<label>' | 'anon'
  action   text not null,
  team_id  integer,
  match_no smallint,
  detail   jsonb not null default '{}'   -- never player names
);
create index audit_log_at_idx on cs2.audit_log (at desc);

create table cs2.throttle (
  key          text primary key,   -- 'login:<label>' | 'setup'
  fails        integer not null default 0,
  window_start timestamptz not null default now(),
  until        timestamptz
);

